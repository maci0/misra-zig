import { readFileSync } from "node:fs";
import { join, relative } from "node:path";
import { projectRoot, zigCommand } from "./check.ts";

/**
 * Reads the installed Zig standard library and writes `tools/std_lists.zig`:
 * - `deprecated`: every top-level `pub` declaration whose doc comment says
 *   "Deprecated", with the replacement the comment names;
 * - `posix_assumes_errno`: every `std.posix` function with an errno prong that
 *   is `=> unreachable`, which is illegal behavior when the OS returns it.
 * `--check` compares instead of writing, and exits 1 when the file is stale.
 */

const OUTPUT = join("tools", "std_lists.zig");
const DECL = /^pub (?:inline )?(?:const|fn|var) ([A-Za-z_][A-Za-z0-9_]*)/;
const ERRNO_UNREACHABLE = /^\s+\.[A-Z][A-Z0-9_]*(?:\s*,\s*\.[A-Z][A-Z0-9_]*)*\s*,?\s*=>\s*unreachable/;

async function zigEnv(): Promise<{ stdDir: string; version: string }> {
    const proc = Bun.spawn({ cmd: [zigCommand(), "env"], stdout: "pipe", stderr: "pipe" });
    const text = await new Response(proc.stdout).text();
    if ((await proc.exited) !== 0) throw new Error("zig env failed");
    const stdDir = /\.std_dir = "([^"]+)"/.exec(text)?.[1];
    const version = /\.version = "([^"]+)"/.exec(text)?.[1];
    if (!stdDir || !version) throw new Error("zig env did not name std_dir and version");
    return { stdDir, version };
}

function namespaceOf(stdDir: string, file: string): string {
    const parts = relative(stdDir, file).replace(/\.zig$/, "").split("/");
    return ["std", ...parts].join(".");
}

/** A doc line that marks the declaration deprecated: "Deprecated ..." or "This function is deprecated ...". */
const DEPRECATED_LINE = /^\/\/\/\s*(?:Deprecated\b|This (?:function|declaration|type|constant) is deprecated\b)/im;

/** The replacement a deprecation comment names, such as `mem.print` or `@memmove`, or "". */
function replacementOf(doc: string): string {
    return /deprecated[^`]*`([^`]+)`/i.exec(doc)?.[1] ?? /deprecated; use (@?[A-Za-z_][\w.]*) instead/i.exec(doc)?.[1] ?? "";
}

function deprecatedIn(stdDir: string, file: string): [string, string][] {
    const found: [string, string][] = [];
    let doc: string[] = [];
    for (const line of readFileSync(file, "utf8").split("\n")) {
        if (line.startsWith("///")) {
            doc.push(line);
            continue;
        }
        const name = DECL.exec(line)?.[1];
        const text = doc.join(" ");
        if (name && DEPRECATED_LINE.test(doc.join("\n"))) found.push([`${namespaceOf(stdDir, file)}.${name}`, replacementOf(text)]);
        doc = [];
    }
    return found;
}

function posixAssumptions(stdDir: string): string[] {
    const names = new Set<string>();
    let current: string | null = null;
    for (const line of readFileSync(join(stdDir, "posix.zig"), "utf8").split("\n")) {
        const start = /^pub fn ([A-Za-z_][A-Za-z0-9_]*)\(/.exec(line)?.[1];
        if (start) current = start;
        else if (/^(?:fn |pub |const |\})/.test(line)) current = line.startsWith("}") ? current : null;
        if (current && ERRNO_UNREACHABLE.test(line)) names.add(current);
    }
    return [...names].sort();
}

function zigString(text: string): string {
    return JSON.stringify(text);
}

export async function renderStdLists(): Promise<string> {
    const { stdDir, version } = await zigEnv();
    const deprecated: [string, string][] = [];
    for (const rel of new Bun.Glob("**/*.zig").scanSync({ cwd: stdDir })) {
        deprecated.push(...deprecatedIn(stdDir, join(stdDir, rel)));
    }
    deprecated.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
    const posix = posixAssumptions(stdDir);
    const lines = [
        `//! Generated by \`bun scripts/gen_std_lists.ts\` from the Zig ${version} standard library. Do not edit.`,
        "",
        "/// Top-level std declarations marked deprecated, and the replacement each one names.",
        "pub const deprecated = [_][2][]const u8{",
        ...deprecated.map(([name, hint]) => `    .{ ${zigString(name)}, ${zigString(hint)} },`),
        "};",
        "",
        "/// std.posix functions with an errno prong that is `=> unreachable`.",
        "pub const posix_assumes_errno = [_][]const u8{",
        ...posix.map((name) => `    ${zigString(name)},`),
        "};",
        "",
    ];
    return lines.join("\n");
}

if (import.meta.main) {
    const root = projectRoot(import.meta.dir);
    const text = await renderStdLists();
    const path = join(root, OUTPUT);
    if (Bun.argv.includes("--check")) {
        const current = await Bun.file(path).text().catch(() => "");
        if (current !== text) {
            console.error(`${OUTPUT} is stale; run bun scripts/gen_std_lists.ts`);
            process.exit(1);
        }
        console.log(`${OUTPUT} matches the installed std`);
    } else {
        await Bun.write(path, text);
        console.log(`wrote ${OUTPUT}`);
    }
}
